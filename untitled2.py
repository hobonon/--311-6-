from tensorflow import keras

# matplotlib — графики и вывод картинок; numpy — массивы и вычисления;
# TensorFlow/Keras — создание и обучение нейросети, содержит датасет Fashion MNIST.

(x_train, y_train), (x_test, y_test) = keras.datasets.fashion_mnist.load_data()
class_names = ['Футболка/топ', 'Брюки', 'Свитер', 'Платье', 'Пальто',
               'Сандалия', 'Рубашка', 'Кроссовок', 'Сумка', 'Ботинок']

# 1. Все типы вещей
for i, name in enumerate(class_names):
    print(i, '-', name)
plt.figure(figsize=(12, 5))
for i in range(10):
    plt.subplot(2, 5, i + 1)
    plt.imshow(x_train[np.where(y_train == i)[0][0]], cmap='gray')
    plt.title(class_names[i]); plt.axis('off')
plt.tight_layout(); plt.show()

# 2. Обучение модели
x_train, x_test = x_train / 255.0, x_test / 255.0
model = keras.Sequential([
    keras.layers.Flatten(input_shape=(28, 28)),
    keras.layers.Dense(128, activation='relu'),
    keras.layers.Dense(10, activation='softmax')
])
model.compile(optimizer='adam', loss='sparse_categorical_crossentropy', metrics=['accuracy'])
model.fit(x_train, y_train, epochs=10, validation_data=(x_test, y_test))
print('Точность на тесте:', model.evaluate(x_test, y_test, verbose=0)[1])

# 3. Примеры вещей и их тип
pred = np.argmax(model.predict(x_test[:10]), axis=1)
plt.figure(figsize=(14, 6))
for i in range(10):
    plt.subplot(2, 5, i + 1)
    plt.imshow(x_test[i], cmap='gray')
    plt.title(f'{class_names[pred[i]]}\n(факт: {class_names[y_test[i]]})',
              color='green' if pred[i] == y_test[i] else 'red', fontsize=9)
    plt.axis('off')
plt.tight_layout(); plt.show()